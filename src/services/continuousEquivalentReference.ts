/**
 * 連續文本當量的參考分佈
 *
 * 參考曲線的 μ / σ 直接取自各方案 JSON 裡存好的 測評結果.連續文本當量，
 * 不再另外生成一份常量表——那份表遲早會和方案 JSON 對不上口徑。
 * 代價是參考只覆蓋方案存檔用的那個窗口長度（重算腳本固定爲 100 字）：
 * 用戶把窗口改成别的值時查不到參考，這是對的，
 * 拿窗口 100 的 σ 去比窗口 20 的分佈只會得出錯誤結論。
 */

import type { 方案配置介面 } from '@/types/scheme'
import type { 連續文本當量碼表口徑 } from '@/atoms/continuousEquivalent'

/** 一組常態分佈參數 */
export interface 參考分佈項介面 {
  平均數: number
  標準差: number
}

/** 下拉選單裡的一個參考方案 */
export interface 參考方案項介面 {
  鍵名: string
  方案名: string
}

/**
 * 頁面默認選中的參考方案
 *
 * 卿雲是文檔和討論裡最常拿來做基準的方案，所以固定默認選它；
 * 該方案不在列表裡（比如被停用了）時退回列表第一項。
 */
export const 默認參考方案鍵名 = 'yuhao-joy'

/**
 * 從方案列表中挑出能當參考的那些
 *
 * 順序照搬傳入的方案列表（即 builtin-schemes.json 的順序），
 * 没有連續文本當量存檔的方案不會出現在選單裡。
 */
export function 取可用參考方案(方案列表: 方案配置介面[]): 參考方案項介面[] {
  return 方案列表
    .filter(方案 => 方案.測評結果?.連續文本當量?.統計)
    .map(方案 => ({ 鍵名: 方案.元數據.標識符, 方案名: 方案.元數據.方案名 }))
}

/**
 * 取某個參考方案的分佈參數
 *
 * @param 窗口長度 當前圖上用的窗口長度；與存檔不一致時返回 undefined
 * @returns 平均數與標準差；查不到時返回 undefined
 */
export function 取參考分佈(
  方案列表: 方案配置介面[],
  鍵名: string,
  口徑: 連續文本當量碼表口徑,
  窗口長度: number
): 參考分佈項介面 | undefined {
  const 存檔 = 方案列表.find(方案 => 方案.元數據.標識符 === 鍵名)?.測評結果?.連續文本當量
  if (!存檔 || 存檔.窗口長度 !== 窗口長度) return undefined

  const 統計 = 存檔.統計?.[口徑]
  if (!統計) return undefined

  return { 平均數: 統計.平均數, 標準差: 統計.標準差 }
}

/** 取參考方案存檔用的窗口長度，用於在窗口對不上時給出提示 */
export function 取參考窗口長度(方案列表: 方案配置介面[], 鍵名: string): number | undefined {
  return 方案列表.find(方案 => 方案.元數據.標識符 === 鍵名)?.測評結果?.連續文本當量?.窗口長度
}

/** 取參考方案的顯示名 */
export function 取參考方案名(方案列表: 方案配置介面[], 鍵名: string): string {
  return 方案列表.find(方案 => 方案.元數據.標識符 === 鍵名)?.元數據.方案名 ?? 鍵名
}
