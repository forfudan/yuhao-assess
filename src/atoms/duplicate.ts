/**
 * 重碼分析原子狀態
 * 存儲重碼分析的統計結果（可導出到 JSON）
 */

import { atomWithStorage } from 'jotai/utils'

/**
 * 動態選重率結果介面（單個字頻源）
 */
export interface 動態選重率結果介面 {
  全碼: number
  簡碼: number
}

/**
 * 靜態重碼結果（單個字符集）
 */
