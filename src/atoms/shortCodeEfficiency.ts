/**
 * 簡碼效率分析 Atom 狀態
 */

import { atom } from 'jotai'

/**
 * 單個字頻類型的簡碼效率結果
 */
export interface 單字頻簡碼效率結果介面 {
  /**
   * 最有效率的簡碼個數
   */
  最有效率的簡碼個數: number

  /**
   * 簡碼效率值（平均碼長）
   */
  簡碼效率值: number

  /**
   * 對應字符字符串
   */
  對應字符字符串: string
}

/**
 * 完整的簡碼效率分析結果
 * 包含所有字頻類型的結果
 */
export interface 簡碼效率分析結果介面 {
  /**
   * 知乎簡體字頻的簡碼效率結果
   */
  知乎簡體字頻結果: 單字頻簡碼效率結果介面[]

  /**
   * 北語簡體字頻的簡碼效率結果
   */
  北語簡體字頻結果: 單字頻簡碼效率結果介面[]

  /**
   * 臺標繁體字頻的簡碼效率結果
   */
  臺標繁體字頻結果: 單字頻簡碼效率結果介面[]

  /**
   * 古籍繁體字頻的簡碼效率結果
   */
  古籍繁體字頻結果: 單字頻簡碼效率結果介面[]

  /**
   * 繁簡聯合字頻的簡碼效率結果
   */
  繁簡聯合字頻結果: 單字頻簡碼效率結果介面[]

  /**
   * 計算時間戳
   */
  計算時間: number
}

/**
 * 簡碼效率分析結果的原子狀態
 * 全局狀態，可以被導入導出
 */
export const 簡碼效率分析原子狀態 = atom<簡碼效率分析結果介面 | null>(null)
