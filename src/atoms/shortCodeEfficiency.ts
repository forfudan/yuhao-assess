/**
 * 簡碼效率分析 Atom 狀態
 */

import { atom } from 'jotai'

/**
 * 單個 N 值的簡碼效率結果（不含字符串）
 */
export interface N值簡碼效率結果介面 {
  /**
   * 最有效率的簡碼個數
   */
  最有效率的簡碼個數: number

  /**
   * 簡碼效率值（平均碼長）
   */
  簡碼效率值: number
}

/**
 * 單個字頻類型的簡碼效率結果
 * 包含完整字符串（最大 N 值對應）和所有 N 值的效率數據
 */
export interface 單個字頻簡碼效率結果介面 {
  /**
   * 完整字符字符串（最大 N 值時的所有字符）
   * 其他 N 值的字符可通過截取前 N 個字符獲得
   */
  完整字符字符串: string

  /**
   * 所有 N 值的效率結果
   */
  N值結果: N值簡碼效率結果介面[]
}

/**
 * 完整的簡碼效率分析結果
 * 包含所有字頻類型的結果
 */
export interface 簡碼效率分析結果介面 {
  /**
   * 知乎簡體字頻的簡碼效率結果
   */
  知乎簡體字頻下之簡碼效率: 單個字頻簡碼效率結果介面

  /**
   * 北語簡體字頻的簡碼效率結果
   */
  北語簡體字頻下之簡碼效率: 單個字頻簡碼效率結果介面

  /**
   * 臺標繁體字頻的簡碼效率結果
   */
  臺標繁體字頻下之簡碼效率: 單個字頻簡碼效率結果介面

  /**
   * 古籍繁體字頻的簡碼效率結果
   */
  古籍繁體字頻下之簡碼效率: 單個字頻簡碼效率結果介面

  /**
   * 繁簡聯合字頻的簡碼效率結果
   */
  繁簡聯合字頻下之簡碼效率: 單個字頻簡碼效率結果介面

  /**
   * 計算時間戳
   */
  計算時間: number
}

/**
 * 簡碼效率分析結果的原子狀態
 * 全局狀態，可以被導入導出
 */
export const 簡碼效率分析原子狀態 = atom<簡碼效率分析結果介面 | null>(null)
