/**
 * 主题配置类型定义
 */

/**
 * 表格样式配置
 */
export interface 表格样式配置 {
  /** 表格字体大小（单位：px） */
  字体大小: number
  /** 单元格垂直内边距（单位：px） */
  单元格垂直内边距: number
  /** 单元格水平内边距（单位：px） */
  单元格水平内边距: number
  /** 表头背景色 */
  表头背景色: string
  /** 表头文字颜色 */
  表头文字颜色: string
}

/**
 * 主题配置
 */
export interface 主题配置 {
  /** 全局字体大小（单位：px） */
  全局字体大小: number
  /** 全局行高 */
  全局行高: number
  /** 表格样式 */
  表格: 表格样式配置
}

/**
 * 默认主题配置
 */
export const 默认主题配置: 主题配置 = {
  全局字体大小: 14,
  全局行高: 1.4,
  表格: {
    字体大小: 13,
    单元格垂直内边距: 4,
    单元格水平内边距: 8,
    表头背景色: '#f8f9fa',
    表头文字颜色: '#212529',
  },
}
